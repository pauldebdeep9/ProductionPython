"""
01 — Static vs runtime: the distinction everything else depends on.

THE ONE-PARAGRAPH VERSION
-------------------------
Python annotations do NOTHING at runtime. `def f(x: int)` accepts a string, a
list, or a socket without complaint. mypy reads annotations and checks them
before your code runs; the interpreter ignores them entirely.

That means annotations are a *proof about code you control* and a *lie about
data you receive*. The same `x: int` is load-bearing inside your package and
worthless on a JSON payload from an HTTP client or an LLM.

So there are two separate tools for two separate jobs:

    STATIC (mypy)      proves internal consistency. Free at runtime.
                       Catches: wrong argument order, None where a value was
                       required, a refactor that missed a call site.

    RUNTIME (Pydantic) validates untrusted data at a boundary. Costs CPU.
                       Catches: the API returned null for a required field,
                       the model emitted "0.85" instead of 0.85, a client
                       sent an extra field you should reject.

Using one where the other belongs is the most common typing mistake in
production Python. Runtime-validating your own internal function arguments is
wasted CPU and noise. Statically typing untrusted input is a comforting lie.

Run:  python 01_static_vs_runtime.py
      mypy --strict 01_static_vs_runtime.py
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, cast

from typing_lab import (
    ChunkId,
    Completion,
    CompletionPayload,
    DeploymentName,
    DocId,
    FinishReason,
    Usage,
    banner,
    section,
    show,
)


# ---------------------------------------------------------------------------
# PART 1 — annotations do nothing
# ---------------------------------------------------------------------------

def add_scores(a: float, b: float) -> float:
    return a + b


def part1_annotations_are_inert() -> None:
    banner("PART 1 — annotations are not enforced at runtime")

    show("add_scores(1.5, 2.5)", add_scores(1.5, 2.5))

    # This is a static type error that mypy reports, and the interpreter runs
    # happily — because `+` happens to be defined for strings.
    #
    # The `type: ignore` comment tells mypy we are doing this deliberately.
    # ALWAYS give it a specific error code and a reason; a bare `# type: ignore`
    # suppresses every future error on that line too, including ones you
    # would want to know about.
    bad = add_scores("1.5", "2.5")  # type: ignore[arg-type]  # deliberate demo
    show('add_scores("1.5", "2.5")', repr(bad))
    print("""
    No exception. `+` is defined for str, so Python does string concatenation
    and returns "1.52.5" where every downstream consumer expects a float.

    This is the shape of the whole class of bug: the failure surfaces far from
    its cause, as a weird value rather than an error. mypy catches it at the
    call site, in the editor, in CI — before it ever runs.""")

    show("__annotations__ at runtime", add_scores.__annotations__)
    print("    ...just a dict. Nothing reads it unless you write code that does.")


