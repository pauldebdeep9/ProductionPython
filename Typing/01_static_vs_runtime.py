# PART 6 — what static typing actually catches
# ---------------------------------------------------------------------------

@dataclass
class Retriever:
    top_k: int = 5

    def search(self, query: str, groups: frozenset[str]) -> list[ChunkId]:
        return [ChunkId("c1")]


def part6_what_it_catches() -> None:
    banner("PART 6 — the bugs static typing actually catches")

    print("""
    Real bugs, in rough order of how often mypy catches them in practice:

    1. ARGUMENT ORDER / NAME after a refactor
         search(groups, query)  — both are "stringish", tests may pass with
         symmetric fixtures. NewType (DocId vs ChunkId) makes even same-typed
         swaps a checker error.

    2. None WHERE A VALUE IS REQUIRED
         `Optional[Chunk]` returned from a lookup, used without a check. This
         is the single largest category and the reason `strict_optional` is
         on by default.

    3. A MISSED CALL SITE
         You add a required parameter; mypy finds all 14 callers instantly.
         Grep finds 11 of them and misses the ones behind an alias.

    4. IMPOSSIBLE BRANCHES
         Comparing a Literal against a value not in its set, or an `if` on a
         union member already excluded. mypy flags the dead branch; tests
         never will, because the branch never runs.

    5. RETURN TYPE DRIFT
         A function annotated `-> Completion` that returns `None` on one path.
         Extremely common in error handling, and invisible until that path
         runs in production.

    WHAT IT DOES NOT CATCH, and it matters that you know:
      * wrong VALUES (a score of 1.5 where 0-1 was meant)
      * wrong LOGIC (retrieving the wrong chunks, correctly typed)
      * anything about untrusted input
      * anything behind an `Any`, a bare `cast`, or an untyped dependency

    Static typing is a proof of internal consistency. It says nothing about
    whether the thing you built is the right thing.""")


def main() -> None:
    part1_annotations_are_inert()
    part2_boundaries()
    part3_typeddict_is_not_validation()
    part4_any_contagion()
    part5_adapter()
    part6_what_it_catches()

    banner("SUMMARY")
    print("""
  * Annotations do nothing at runtime. mypy reads them; Python ignores them.
  * Static typing is load-bearing INSIDE your code; useless on untrusted data.
  * Runtime validation is load-bearing AT boundaries; wasted CPU internally.
  * The forgotten boundary is LLM OUTPUT — the least reliable data source in
    the system, validated less rigorously than the HTTP request body.
  * TypedDict describes a shape; it never checks one.
  * `cast()` is an unverified assertion. Legitimate only when you have just
    performed the check the checker cannot see.
  * `Any` means "stop checking" and spreads through every expression it
    touches. Prefer `object`, which forces narrowing.
  * Boundary adapters convert untrusted input into internal types, and that
    transition is where static checking starts being worth anything.
""")


if __name__ == "__main__":
    main()
